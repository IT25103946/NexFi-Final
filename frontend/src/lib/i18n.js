/**
 * Returns a translation function bound to the provided language.
 */
export function getTranslator(language = 'en') {
  const activeLang = ['en', 'si', 'ta'].includes(language) ? language : 'en'
  return function t(key, replacements = {}) {
    const parts = key.split('.')
    let current = translations[activeLang]
    for (const part of parts) {
      current = current?.[part]
      if (current === undefined) break
    }
    // Fall back to English if key missing in selected language
    if (typeof current !== 'string') {
      current = translations.en
      for (const part of parts) {
        current = current?.[part]
        if (current === undefined) break
      }
    }
    if (typeof current !== 'string') return key
    return Object.entries(replacements).reduce(
      (text, [k, v]) => text.replaceAll(`{${k}}`, v),
      current,
    )
  }
}

/**
 * Global helper function for translating keys.
 * Can be called as t(key, replacements) or t(key, replacements, language).
 */
export function t(key, replacements = {}, language) {
  let lang = language
  if (!lang) {
    try {
      lang = localStorage.getItem('nexfi.language') || 'en'
    } catch {
      lang = 'en'
    }
  }
  return getTranslator(lang)(key, replacements)
}
